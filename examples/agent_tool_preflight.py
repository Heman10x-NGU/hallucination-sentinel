"""
Agent Tool Preflight
====================

Shows how to use ``guard_output_from_entropies`` as a pre-flight check
before an agent executes a tool call whose output was generated by an LLM.

The pattern:
  1. The agent plans a tool call and generates the arguments.
  2. The LLM generates arguments with logprobs enabled.
  3. Compute entropy from the logprobs.
  4. Gate the generated arguments through ``guard_output_from_entropies``
     with ``TaskCriticality.CRITICAL``.
  5. If the routing action is BLOCK, skip the tool call and log a warning.

This is useful for agents that write code, send emails, or execute
database queries -- any tool where a hallucinated argument could cause
real damage.

Note: ``guard_output()`` requires real token entropy/logprobs from a provider.
For offline/batch scoring, use ``guard_output_from_entropies()`` with
pre-computed entropy sequences. See docs/limitations.md for details.
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import numpy as np

from hallucination_sentinel.calibration import load_calibration
from hallucination_sentinel.integrations.middleware import (
    PolicyAction,
    RoutingDecision,
    TaskCriticality,
    guard_output_from_entropies,
)


# ---------------------------------------------------------------------------
# Stub tool infrastructure
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ToolCall:
    """A planned tool invocation."""

    name: str
    arguments: str


def plan_tool_call(user_request: str) -> tuple[ToolCall, np.ndarray]:
    """Have the LLM plan a tool call for *user_request*.

    Replace this with your actual agent/LLM call that returns logprobs.
    Returns (tool_call, entropy_array).

    In production, compute entropy from the provider's top-k logprobs
    using ``entropy_from_topk_logprobs()``. Here we simulate with random
    entropies for demonstration.
    """
    # Simulated: the agent decides to run a SQL query
    tool_call = ToolCall(
        name="execute_sql",
        arguments=f"SELECT * FROM users WHERE name = '{user_request}'",
    )

    # Simulate per-token entropy from a real provider.
    # In production, replace with actual entropy computation from logprobs.
    token_count = len(tool_call.arguments.split())
    entropies = np.random.uniform(0.1, 2.0, size=token_count)

    return tool_call, entropies


def execute_tool(tool_call: ToolCall) -> str:
    """Execute *tool_call* and return the result.

    Replace this with your actual tool dispatcher.
    """
    return f"[tool result for {tool_call.name}: {tool_call.arguments}]"


# ---------------------------------------------------------------------------
# Preflight gate
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class PreflightResult:
    """Outcome of the pre-flight check."""

    tool_call: ToolCall
    decision: RoutingDecision
    executed: bool
    result: Optional[str] = None
    blocked_reason: Optional[str] = None


def agent_tool_preflight(
    user_request: str,
    calibration_path: str,
) -> PreflightResult:
    """Plan a tool call and gate it before execution.

    Args:
        user_request: The user's natural-language request.
        calibration_path: Path to a calibration artifact JSON file.

    Returns:
        A :class:`PreflightResult` describing what happened.
    """
    calibration = load_calibration(calibration_path)

    # 1. Plan the tool call (with entropy from logprobs)
    tool_call, entropies = plan_tool_call(user_request)

    # 2. Gate the generated arguments using pre-computed entropy
    #    We use CRITICAL policy because tool calls can have side effects.
    decision = guard_output_from_entropies(
        user_request,
        tool_call.arguments,
        entropies,
        calibration=calibration,
        provider="openai",
        policy=TaskCriticality.CRITICAL,
    )

    # 3. Act on the decision
    if decision.action is PolicyAction.BLOCK:
        return PreflightResult(
            tool_call=tool_call,
            decision=decision,
            executed=False,
            blocked_reason=(
                "Tool call blocked: CES score indicates high hallucination risk "
                "in the generated arguments.  Review the diagnostic_peaks for "
                "regions of uncertainty."
            ),
        )

    if decision.action is PolicyAction.HUMAN_REVIEW:
        return PreflightResult(
            tool_call=tool_call,
            decision=decision,
            executed=False,
            blocked_reason=(
                "Tool call requires human review before execution. "
                f"CES score: {decision.ces_score:.4f}, "
                f"risk level: {decision.risk_level.value}."
            ),
        )

    # ALLOW / WARN / REQUIRE_EVIDENCE => execute (WARN logs but proceeds)
    result = execute_tool(tool_call)
    return PreflightResult(
        tool_call=tool_call,
        decision=decision,
        executed=True,
        result=result,
    )


# ---------------------------------------------------------------------------
# CLI demo
# ---------------------------------------------------------------------------


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: python agent_tool_preflight.py <calibration.json>")
        print()
        print("Demonstrates agent tool-call preflight gating.")
        sys.exit(1)

    calibration_path = sys.argv[1]
    request = "Find all users with the name Alice"

    result = agent_tool_preflight(request, calibration_path)

    output = {
        "tool_call": {
            "name": result.tool_call.name,
            "arguments": result.tool_call.arguments,
        },
        "executed": result.executed,
        "result": result.result,
        "blocked_reason": result.blocked_reason,
        "decision": result.decision.to_dict(),
    }
    print(json.dumps(output, indent=2))


if __name__ == "__main__":
    main()
